import { describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { parseNpmDependencies } from "../src/ecosystems/npm.js";
import { parseBunLock, parsePnpmLock, parseYarnLock } from "../src/ecosystems/npm-lockfiles.js";

const label = (deps: Array<{ name: string; version: string }>) => deps.map(d => `${d.name}@${d.version}`).sort();
const tmp = () => mkdtempSync(join(tmpdir(), "bugoslav-"));
const write = (dir: string, name: string, content: unknown) => {
  const path = join(dir, name);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, typeof content === "string" ? content : JSON.stringify(content));
};

const YARN_V1 = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@s/c@^3.0.0":
  version "3.1.0"
  resolved "https://registry.yarnpkg.com/@s/c/-/c-3.1.0.tgz#abc"

a@^1.0.0, a@^1.1.0:
  version "1.2.0"
  dependencies:
    b "^2.0.0"

b@^2.0.0:
  version "2.0.0"

b@^1.0.0:
  version "1.0.5"

gitdep@github:user/repo:
  version "0.0.1"
`;

const YARN_BERRY = `# This file is generated by running "yarn install"

__metadata:
  version: 8

"a@npm:^1.0.0":
  version: 1.2.0
  resolution: "a@npm:1.2.0"

"b@npm:^2.0.0":
  version: 2.0.0
  resolution: "b@npm:2.0.0"

"fsevents@patch:fsevents@npm%3A2.3.2#~builtin<compat/fsevents>":
  version: 2.3.2
  resolution: "fsevents@patch:fsevents@npm%3A2.3.2#~builtin<compat/fsevents>::version=2.3.2"

"app@workspace:.":
  version: 0.0.0-use.local
  resolution: "app@workspace:."
`;

describe("yarn.lock", () => {
  test("v1: reads registry packages and skips git dependencies", () => {
    expect(label(parseYarnLock(YARN_V1))).toEqual(["@s/c@3.1.0", "a@1.2.0", "b@1.0.5", "b@2.0.0"]);
  });
  test("v1: fast keeps the version matching the declared range", () => {
    const declared = new Map([["a", new Set(["^1.0.0"])], ["b", new Set(["^1.0.0"])]]);
    expect(label(parseYarnLock(YARN_V1, declared))).toEqual(["a@1.2.0", "b@1.0.5"]);
  });
  test("Berry: skips workspaces and patches", () => {
    expect(label(parseYarnLock(YARN_BERRY))).toEqual(["a@1.2.0", "b@2.0.0"]);
    expect(label(parseYarnLock(YARN_BERRY, new Map([["b", new Set(["^2.0.0"])]])))).toEqual(["b@2.0.0"]);
  });
  test("resolves npm: aliases to the real package", () => {
    const lock = `x@npm:real@^1.0.0:\n  version "1.4.0"\n`;
    expect(label(parseYarnLock(lock))).toEqual(["real@1.4.0"]);
    expect(label(parseYarnLock(lock, new Map([["x", new Set(["npm:real@^1.0.0"])]])))).toEqual(["real@1.4.0"]);
  });
});

const PNPM_V9 = `lockfileVersion: '9.0'

importers:

  .:
    dependencies:
      a:
        specifier: ^1.0.0
        version: 1.2.0
    devDependencies:
      '@s/c':
        specifier: ^3.0.0
        version: 3.0.0(react@18.0.0)

  packages/lib:
    dependencies:
      local:
        specifier: workspace:*
        version: link:../other

packages:

  a@1.2.0:
    resolution: {integrity: sha512-x}

  '@s/c@3.0.0':
    resolution: {integrity: sha512-y}

  b@2.0.0:
    resolution: {integrity: sha512-z}

  tarball-dep@https://codeload.github.com/u/r/tar.gz/abc:
    resolution: {tarball: https://codeload.github.com/u/r/tar.gz/abc}

snapshots:

  a@1.2.0:
    dependencies:
      b: 2.0.0
`;

const PNPM_V5 = `lockfileVersion: 5.4

specifiers:
  a: ^1.0.0

dependencies:
  a: 1.2.0_react@18.0.0

packages:

  /@s/c/3.0.0:
    resolution: {integrity: sha512-y}
    dev: false

  /a/1.2.0_react@18.0.0:
    resolution: {integrity: sha512-x}
    dev: false

  /b/2.0.0:
    resolution: {integrity: sha512-z}
    dev: false
`;

describe("pnpm-lock.yaml", () => {
  test("v9: all packages, registry only", () => {
    expect(label(parsePnpmLock(PNPM_V9, false))).toEqual(["@s/c@3.0.0", "a@1.2.0", "b@2.0.0"]);
  });
  test("v9: fast keeps importer dependencies", () => {
    expect(label(parsePnpmLock(PNPM_V9, true))).toEqual(["@s/c@3.0.0", "a@1.2.0"]);
  });
  test("v5: keys with a slash and peer suffix", () => {
    expect(label(parsePnpmLock(PNPM_V5, false))).toEqual(["@s/c@3.0.0", "a@1.2.0", "b@2.0.0"]);
    expect(label(parsePnpmLock(PNPM_V5, true))).toEqual(["a@1.2.0"]);
  });
});

const BUN_LOCK = `{
  "lockfileVersion": 1,
  "workspaces": {
    "": { "name": "root", "dependencies": { "a": "^1.0.0" }, "devDependencies": { "@s/c": "^3.0.0" } },
    "packages/lib": { "name": "lib", "dependencies": { "b": "^1.0.0" } },
  },
  "packages": {
    "a": ["a@1.2.0", "", { "dependencies": { "b": "^2.0.0" } }, "sha512-a,}"],
    "@s/c": ["@s/c@3.0.0", "", {}, "sha512-c"],
    "a/b": ["b@2.0.0", "", {}, "sha512-b2"],
    "lib/b": ["b@1.0.5", "", {}, "sha512-b1"],
    "lib": ["lib@workspace:packages/lib"],
    "gitdep": ["gitdep@github:user/repo#abc", {}, "abc"],
  },
}
`;

describe("bun.lock", () => {
  test("reads registry packages, tolerating trailing commas", () => {
    expect(label(parseBunLock(BUN_LOCK, false))).toEqual(["@s/c@3.0.0", "a@1.2.0", "b@1.0.5", "b@2.0.0"]);
  });
  test("fast keeps top-level and workspace-level direct dependencies", () => {
    expect(label(parseBunLock(BUN_LOCK, true))).toEqual(["@s/c@3.0.0", "a@1.2.0", "b@1.0.5"]);
  });
});

describe("npm project discovery", () => {
  test("a monorepo is covered by the root lockfile, including workspace members", () => {
    const dir = tmp();
    write(dir, "package.json", { workspaces: ["packages/*"], dependencies: { a: "^1.0.0" } });
    write(dir, "packages/lib/package.json", { dependencies: { b: "^2.0.0" } });
    write(dir, "pnpm-lock.yaml", PNPM_V9);
    expect(label(parseNpmDependencies(dir, "all"))).toEqual(["@s/c@3.0.0", "a@1.2.0", "b@2.0.0"]);
    expect(parseNpmDependencies(dir, "all").every(d => d.manifest === "pnpm-lock.yaml")).toBe(true);
  });
  test("independent projects use their own lockfile; one without a lockfile falls back to package.json", () => {
    const dir = tmp();
    write(dir, "web/package.json", { dependencies: { a: "^1.0.0" } });
    write(dir, "web/yarn.lock", YARN_V1);
    write(dir, "tool/package.json", { dependencies: { z: "^9.1.0" } });
    expect(parseNpmDependencies(dir, "fast").map(d => `${d.name}@${d.version} ${d.manifest}`).sort()).toEqual([
      "a@1.2.0 web/yarn.lock",
      "z@9.1.0 tool/package.json",
    ]);
  });
  test("workspace member's own node_modules entry counts as direct in package-lock.json", () => {
    const dir = tmp();
    write(dir, "package.json", { workspaces: ["packages/*"] });
    write(dir, "packages/lib/package.json", { dependencies: { b: "^2.0.0" } });
    write(dir, "package-lock.json", {
      packages: {
        "": {},
        "node_modules/b": { version: "1.0.0" },
        "packages/lib/node_modules/b": { version: "2.0.0" },
        "node_modules/other/node_modules/b": { version: "3.0.0" },
      },
    });
    expect(label(parseNpmDependencies(dir, "fast"))).toEqual(["b@1.0.0", "b@2.0.0"]);
  });
  test("a directory without package.json or lockfiles yields nothing", () => {
    expect(parseNpmDependencies(tmp(), "all")).toEqual([]);
  });
});
